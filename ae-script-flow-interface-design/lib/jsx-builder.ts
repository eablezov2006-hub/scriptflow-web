import type { Expression } from '@/lib/presets'

const PROPERTY_MATCH_NAMES: Record<string, string> = {
  Position: 'ADBE Position',
  Scale: 'ADBE Scale',
  Rotation: 'ADBE Rotate Z',
  Opacity: 'ADBE Opacity',
  'Source Text': 'ADBE Text Document',
}

export function buildAfterEffectsJsx(expr: Expression): string {
  const sliderDefs: { varName: string; sliderName: string; defaultValue: number }[] = []

  // Находим числовые переменные вида `var amp = 0.12;` и превращаем их в ползунки AE
  const rewrittenExpression = expr.code.replace(
    /^(\s*var\s+([a-zA-Z_$][\w$]*)\s*=\s*)(-?\d+(?:\.\d+)?)\s*;/gm,
    (fullMatch, prefix, varName, numStr) => {
      const val = Number(numStr)
      if (!Number.isFinite(val)) return fullMatch

      // Не выносим в ползунки булевы флаги или количество ключевых кадров
      if (varName === 'numKeyframes' || varName === 'octaves') return fullMatch

      const sliderName =
        'SF - ' +
        varName
          .replace(/([A-Z])/g, ' $1')
          .replace(/^./, (s) => s.toUpperCase())
          .trim()

      sliderDefs.push({ varName, sliderName, defaultValue: val })
      return `${prefix}effect("${sliderName}")("ADBE Slider Control-0001");`
    }
  )

  const matchName = PROPERTY_MATCH_NAMES[expr.property] || ''
  const escapedExpression = JSON.stringify(rewrittenExpression)
  const slidersJson = JSON.stringify(sliderDefs)

  return `// Generated by ScriptFlow Pro (scriptflow.app)
// How to run in After Effects:
// 1. Select one or more layers in your composition
// 2. Go to File > Scripts > Run Script File... and select this .jsx file

(function applyScriptFlowEffect() {
  var comp = app.project.activeItem;
  if (!(comp instanceof CompItem)) {
    alert("ScriptFlow: Please open a composition first.");
    return;
  }

  var layers = comp.selectedLayers;
  if (layers.length === 0) {
    alert("ScriptFlow: Please select at least one layer first.");
    return;
  }

  var targetMatchName = ${JSON.stringify(matchName)};
  var expressionCode = ${escapedExpression};
  var sliders = ${slidersJson};

  app.beginUndoGroup("ScriptFlow: ${expr.property}");

  try {
    var appliedCount = 0;

    for (var i = 0; i < layers.length; i++) {
      var layer = layers[i];
      var prop = null;

      if (targetMatchName === "ADBE Text Document") {
        var textGroup = layer.property("ADBE Text Properties");
        if (textGroup) prop = textGroup.property("ADBE Text Document");
      } else if (targetMatchName !== "") {
        var transformGroup = layer.property("ADBE Transform Group");
        if (transformGroup) prop = transformGroup.property(targetMatchName);
      } else if (layer.selectedProperties && layer.selectedProperties.length > 0) {
        for (var p = 0; p < layer.selectedProperties.length; p++) {
          if (layer.selectedProperties[p].canSetExpression) {
            prop = layer.selectedProperties[p];
            break;
          }
        }
      }

      if (!prop || !prop.canSetExpression) {
        continue;
      }

      // Создаём визуальные ползунки Slider Control на слое
      var effectsGroup = layer.property("ADBE Effect Parade");
      if (effectsGroup) {
        for (var s = 0; s < sliders.length; s++) {
          var def = sliders[s];
          var existing = effectsGroup.property(def.sliderName);
          if (!existing) {
            var slider = effectsGroup.addProperty("ADBE Slider Control");
            slider.name = def.sliderName;
            slider.property("ADBE Slider Control-0001").setValue(def.defaultValue);
          }
        }
      }

      prop.expression = expressionCode;
      appliedCount++;
    }

    if (appliedCount === 0) {
      alert(
        "ScriptFlow: Could not find target property (${expr.property}) on the selected layer(s)." +
        (targetMatchName === "" ? "\\nPlease select the specific property in the timeline before running this script." : "")
      );
    }
  } catch (err) {
    alert("ScriptFlow Error: " + err.toString());
  } finally {
    app.endUndoGroup();
  }
})();
`
}
